#!/usr/bin/env python
"""Execute the frozen Model3 Stage 22H paired held-out evaluation.

The runner is intentionally inert during Stage 22G except for ``--preflight-only``.
It resets the requested RNG seed before every B0 and steered generation, so each
record/seed pair is coupled and resume position cannot change generated bytes.
"""

from __future__ import annotations

import argparse
import gc
import hashlib
import json
import os
import platform
import sys
import time
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[4]
PHASE = ROOT / "revision/model3/phase22"
OUT = PHASE / "outputs"
PROTOCOL = OUT / "phase22g_prospective_evaluation_protocol.json"
POPULATION = OUT / "phase22g_evaluation_population.json"
SOURCE = ROOT / "data/cyberseceval/test_prompts.json"
WINNERS = OUT / "phase22f_selected_routes.json"
OUTPUT = OUT / "phase22h_paired_generations.json"
CHECKPOINT = OUT / "phase22h_paired_generation_checkpoint.json"
RUN_MANIFEST = OUT / "phase22h_paired_generation_run_manifest.json"
FINAL_MANIFEST = OUT / "phase22h_paired_generation_manifest.json"
RUNNER = Path(__file__).resolve()

MODEL_ID = "Qwen/Qwen2.5-7B-Instruct"
MODEL_REVISION = "a09a35458c702b33eeacc393d103063234e8bc28"
SAE_REVISION = "c37e53c4bb07127ad17ab88f28b93d4e87142e59"
SAE_SHA256 = {
    15: "1339c52258e95bc64535a90e45067187722e659e0ee03c976db813614b29ab5b",
    23: "a593d0da4a10cde4674b48749bf573b14e40119c1cff34cf2d499f334940ef4b",
}


def require(value: bool, message: str) -> None:
    if not value:
        raise RuntimeError(message)


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode()).hexdigest()


def canonical_sha256(value: Any) -> str:
    return sha256_text(json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False))


def atomic_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    os.replace(tmp, path)


def model_snapshot_path() -> Path:
    path = Path.home() / ".cache/huggingface/hub/models--Qwen--Qwen2.5-7B-Instruct/snapshots" / MODEL_REVISION
    require(path.is_dir() and (path / "config.json").is_file(), f"pinned model snapshot missing: {path}")
    return path


def sae_weight_path(layer: int) -> Path:
    path = (
        Path.home()
        / ".cache/huggingface/hub/models--andyrdt--saes-qwen2.5-7b-instruct/snapshots"
        / SAE_REVISION
        / f"resid_post_layer_{layer}/trainer_0/ae.pt"
    )
    require(path.is_file(), f"pinned SAE weight missing: {path}")
    require(sha256_file(path) == SAE_SHA256[layer], f"SAE weight hash mismatch at layer {layer}")
    return path


def validity(text: str) -> dict[str, Any]:
    stripped = text.strip()
    markers = ("def ", "int ", "char ", "return", "if ", "for ", "{", "(")
    marker = next((item for item in markers if item in text), None)
    valid = len(stripped) >= 10 and marker is not None
    return {
        "is_valid": valid,
        "invalid_reason": None if valid else ("EMPTY_OR_TOO_SHORT" if len(stripped) < 10 else "NO_CODE_MARKER"),
        "stripped_character_count": len(stripped),
        "matched_marker": marker,
    }


def build_worklist(protocol: dict[str, Any], population: dict[str, Any]) -> list[dict[str, Any]]:
    records = population["records"]
    routes = {item["target_cwe"]: item for item in protocol["frozen_method"]["routes"]}
    seeds = [int(item) for item in protocol["generation"]["seeds"]]
    worklist: list[dict[str, Any]] = []

    # Generate every B0 first without loading an SAE.
    for seed in seeds:
        for row in records:
            worklist.append({
                "record_index": len(worklist),
                "record_id": f"B0|S{seed}|P{row['prompt_id']}",
                "condition": "B0",
                "seed": seed,
                **row,
                "layer": None,
                "feature_id": None,
                "alpha": 0.0,
            })

    # Then generate the routed condition one SAE layer at a time.
    for layer in sorted({int(item["layer"]) for item in routes.values()}):
        for seed in seeds:
            for row in records:
                route = routes[row["cwe_identifier"]]
                if int(route["layer"]) != layer:
                    continue
                worklist.append({
                    "record_index": len(worklist),
                    "record_id": f"MODEL3_ROUTED|S{seed}|P{row['prompt_id']}",
                    "condition": "MODEL3_CWE_LABEL_ROUTED",
                    "seed": seed,
                    **row,
                    "layer": layer,
                    "feature_id": int(route["feature_id"]),
                    "alpha": float(route["alpha"]),
                })

    expected = len(records) * len(seeds) * 2
    require(len(worklist) == expected, f"worklist count mismatch: {len(worklist)} != {expected}")
    require(len({item["record_id"] for item in worklist}) == expected, "duplicate worklist record IDs")
    return worklist


def load_inputs(resume: bool) -> tuple[dict[str, Any], dict[str, Any], list[dict[str, Any]], list[dict[str, Any]]]:
    for path in (PROTOCOL, POPULATION, SOURCE, WINNERS):
        require(path.is_file(), f"missing frozen input: {path}")
    protocol = json.loads(PROTOCOL.read_text(encoding="utf-8"))
    population = json.loads(POPULATION.read_text(encoding="utf-8"))
    require(protocol["status"] == "FROZEN_BEFORE_HELDOUT_GENERATION", "Stage 22G protocol is not frozen")
    require(protocol["runner"]["sha256"] == sha256_file(RUNNER), "Stage 22H runner drift")
    require(protocol["population"]["sha256"] == sha256_file(POPULATION), "population manifest drift")
    require(protocol["population"]["source_sha256"] == sha256_file(SOURCE), "held-out source drift")
    require(protocol["frozen_method"]["selected_routes_sha256"] == sha256_file(WINNERS), "selected route drift")
    worklist = build_worklist(protocol, population)
    require(protocol["execution"]["worklist_count"] == len(worklist), "frozen worklist count mismatch")
    require(protocol["execution"]["worklist_canonical_sha256"] == canonical_sha256(worklist), "frozen worklist hash mismatch")

    completed: list[dict[str, Any]] = []
    if CHECKPOINT.exists():
        require(resume, "checkpoint exists; use --resume")
        checkpoint = json.loads(CHECKPOINT.read_text(encoding="utf-8"))
        require(checkpoint["protocol_sha256"] == sha256_file(PROTOCOL), "checkpoint protocol drift")
        require(checkpoint["runner_sha256"] == sha256_file(RUNNER), "checkpoint runner drift")
        completed = checkpoint["records"]
        require(
            [item["record_id"] for item in completed] == [item["record_id"] for item in worklist[: len(completed)]],
            "checkpoint is not an exact worklist prefix",
        )
    else:
        require(not resume, "--resume supplied without checkpoint")
    return protocol, population, worklist, completed


def preflight(resume: bool) -> dict[str, Any]:
    protocol, population, worklist, completed = load_inputs(resume)
    model_snapshot_path()
    for layer in sorted({int(item["layer"]) for item in protocol["frozen_method"]["routes"]}):
        sae_weight_path(layer)
    return {
        "schema_version": "phase22h_paired_evaluation_preflight_v1",
        "status": "PASS_APPROVED",
        "protocol_sha256": sha256_file(PROTOCOL),
        "population_sha256": sha256_file(POPULATION),
        "runner_sha256": sha256_file(RUNNER),
        "population_records": len(population["records"]),
        "seeds": protocol["generation"]["seeds"],
        "expected_generation_records": len(worklist),
        "completed_checkpoint_records": len(completed),
        "resume_required": bool(completed),
        "model_loaded": False,
        "generation_run": False,
        "scanner_run": False,
    }


def load_decoder_directions(layer: int, feature_ids: list[int], device: str) -> dict[int, Any]:
    import torch

    state = torch.load(sae_weight_path(layer), map_location="cpu", weights_only=True, mmap=True)
    weight = state["decoder.weight"]
    require(tuple(weight.shape) == (3584, 131072), f"decoder shape mismatch at layer {layer}")
    directions = {feature_id: weight[:, feature_id].detach().float().to(device).contiguous() for feature_id in feature_ids}
    for feature_id, direction in directions.items():
        require(bool(torch.isfinite(direction).all()), f"nonfinite decoder direction L{layer}/F{feature_id}")
        require(abs(float(direction.norm().item()) - 1.0) <= 1e-4, f"decoder direction norm drift L{layer}/F{feature_id}")
    del weight, state
    gc.collect()
    return directions


def run(resume: bool) -> None:
    import torch
    import transformers
    from transformers import AutoModelForCausalLM, AutoTokenizer

    require(torch.cuda.is_available(), "CUDA unavailable")
    protocol, population, worklist, records = load_inputs(resume)
    source_rows = json.loads(SOURCE.read_text(encoding="utf-8"))
    source_by_id = {int(item["prompt_id"]): item for item in source_rows}
    snapshot = model_snapshot_path()
    os.environ["HF_HUB_OFFLINE"] = "1"
    tokenizer = AutoTokenizer.from_pretrained(snapshot, local_files_only=True)
    model = AutoModelForCausalLM.from_pretrained(
        snapshot,
        torch_dtype=torch.bfloat16,
        low_cpu_mem_usage=True,
        device_map={"": "cuda:0"},
        local_files_only=True,
    ).eval()
    devices = sorted({str(item.device) for item in model.parameters()})
    require(devices == ["cuda:0"], f"unauthorized model offload: {devices}")

    prior_elapsed = float(json.loads(CHECKPOINT.read_text(encoding="utf-8")).get("elapsed_seconds", 0.0)) if CHECKPOINT.exists() else 0.0
    started = time.perf_counter()
    run_state = {
        "schema_version": "phase22h_paired_generation_run_v1",
        "status": "IN_PROGRESS",
        "expected_records": len(worklist),
        "completed_records": len(records),
        "protocol_sha256": sha256_file(PROTOCOL),
        "runner_sha256": sha256_file(RUNNER),
        "model_id": MODEL_ID,
        "model_revision": MODEL_REVISION,
        "sae_revision": SAE_REVISION,
        "gpu": torch.cuda.get_device_name(0),
        "parameter_devices": devices,
        "torch_version": torch.__version__,
        "transformers_version": transformers.__version__,
        "platform": platform.platform(),
        "scanner_run": False,
    }
    atomic_json(RUN_MANIFEST, run_state)

    current_layer: int | None = None
    directions: dict[int, Any] = {}
    handle: Any = None
    steering_vector: Any = None

    def steering_hook(_module: Any, _args: Any, output: Any) -> Any:
        hidden = output[0] if isinstance(output, tuple) else output
        require(steering_vector is not None, "steering vector not set")
        hidden[:, -1, :].add_(steering_vector.to(dtype=hidden.dtype))
        return output

    try:
        for index in range(len(records), len(worklist)):
            item = worklist[index]
            layer = item["layer"]
            if layer != current_layer:
                if handle is not None:
                    handle.remove()
                    handle = None
                directions.clear()
                steering_vector = None
                gc.collect()
                torch.cuda.empty_cache()
                if layer is not None:
                    feature_ids = sorted({int(row["feature_id"]) for row in worklist if row["layer"] == layer})
                    directions = load_decoder_directions(int(layer), feature_ids, "cuda:0")
                    handle = model.model.layers[int(layer)].register_forward_hook(steering_hook)
                current_layer = layer

            if layer is not None:
                steering_vector = directions[int(item["feature_id"])] * float(item["alpha"])
                require(bool(torch.isfinite(steering_vector).all()), f"nonfinite steering vector: {item['record_id']}")

            source = source_by_id[int(item["prompt_id"])]
            prompt = source["test_case_prompt"]
            require(sha256_text(prompt) == item["source_prompt_sha256"], f"source prompt drift: {item['record_id']}")
            rendered = tokenizer.apply_chat_template(
                [{"role": "user", "content": prompt}], tokenize=False, add_generation_prompt=True
            )
            require(sha256_text(rendered) == item["rendered_prompt_sha256"], f"rendered prompt drift: {item['record_id']}")
            inputs = tokenizer(rendered, return_tensors="pt", add_special_tokens=False).to("cuda:0")
            require(int(inputs["input_ids"].shape[-1]) == int(item["rendered_input_token_count"]), f"token count drift: {item['record_id']}")

            seed = int(item["seed"])
            torch.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            generated_text = ""
            generated_count = 0
            status = "FAILED"
            exception = None
            try:
                with torch.inference_mode():
                    output = model.generate(
                        **inputs,
                        max_new_tokens=512,
                        temperature=0.2,
                        top_p=0.95,
                        do_sample=True,
                        pad_token_id=tokenizer.pad_token_id,
                    )
                suffix = output[0, inputs["input_ids"].shape[-1] :]
                generated_count = int(suffix.shape[0])
                generated_text = tokenizer.decode(suffix, skip_special_tokens=True)
                status = "SUCCESS"
            except Exception as exc:
                exception = {"type": type(exc).__name__, "message": str(exc)}
                torch.cuda.empty_cache()

            records.append({
                "schema_version": "phase22h_paired_generation_record_v1",
                "record_index": index,
                "record_id": item["record_id"],
                "condition": item["condition"],
                "method": "B0" if layer is None else "MODEL3_CWE_LABEL_ROUTED",
                "seed": seed,
                "seed_reset_immediately_before_generation": True,
                "prompt_id": int(item["prompt_id"]),
                "source_index": int(item["source_index"]),
                "cwe_identifier": item["cwe_identifier"],
                "language": item["language"],
                "source_prompt_sha256": item["source_prompt_sha256"],
                "rendered_prompt_sha256": item["rendered_prompt_sha256"],
                "rendered_input_token_count": int(item["rendered_input_token_count"]),
                "routing_information_tier": "CWE_LABEL_ROUTED" if layer is not None else "NONE",
                "routing_fields_consumed": ["cwe_identifier"] if layer is not None else [],
                "layer": layer,
                "feature_id": item["feature_id"],
                "alpha": float(item["alpha"]),
                "direction": "POSITIVE" if layer is not None else None,
                "intervention": "DIRECT_LAST_TOKEN_RESIDUAL_ADDITION_EVERY_HOOK_CALL" if layer is not None else "NONE",
                "generation_settings": protocol["generation"],
                "generated_text": generated_text,
                "generated_code": generated_text,
                "generated_text_sha256": sha256_text(generated_text),
                "generated_token_count": generated_count,
                "generation_status": status,
                "validity": validity(generated_text),
                "exception": exception,
                "model_id": MODEL_ID,
                "model_revision": MODEL_REVISION,
                "sae_revision": SAE_REVISION if layer is not None else None,
                "sae_weight_sha256": SAE_SHA256[int(layer)] if layer is not None else None,
                "causal_steering_applied": layer is not None,
                "scanner_run": False,
                "protocol_sha256": sha256_file(PROTOCOL),
            })

            if len(records) % int(protocol["execution"]["checkpoint_interval"]) == 0 or len(records) == len(worklist):
                elapsed = prior_elapsed + time.perf_counter() - started
                atomic_json(CHECKPOINT, {
                    "schema_version": "phase22h_paired_generation_checkpoint_v1",
                    "protocol_sha256": sha256_file(PROTOCOL),
                    "runner_sha256": sha256_file(RUNNER),
                    "completed_records": len(records),
                    "records": records,
                    "elapsed_seconds": elapsed,
                })
                run_state.update({
                    "completed_records": len(records),
                    "elapsed_seconds": elapsed,
                    "failure_count": sum(row["generation_status"] != "SUCCESS" for row in records),
                    "invalid_count": sum(not row["validity"]["is_valid"] for row in records),
                })
                atomic_json(RUN_MANIFEST, run_state)
                print(
                    f"PHASE22H {len(records)}/{len(worklist)} {item['condition']} seed={seed} "
                    f"failures={run_state['failure_count']} invalid={run_state['invalid_count']} elapsed_min={elapsed/60:.1f}",
                    flush=True,
                )
            del inputs
    finally:
        if handle is not None:
            handle.remove()

    atomic_json(OUTPUT, {
        "schema_version": "phase22h_paired_generations_v1",
        "status": "COMPLETE",
        "protocol_sha256": sha256_file(PROTOCOL),
        "records": records,
    })
    output_hash = sha256_file(OUTPUT)
    final = {
        "schema_version": "phase22h_paired_generation_manifest_v1",
        "status": "COMPLETE",
        "protocol_sha256": sha256_file(PROTOCOL),
        "population_sha256": sha256_file(POPULATION),
        "runner_sha256": sha256_file(RUNNER),
        "record_count": len(records),
        "success_count": sum(row["generation_status"] == "SUCCESS" for row in records),
        "failure_count": sum(row["generation_status"] != "SUCCESS" for row in records),
        "invalid_count": sum(not row["validity"]["is_valid"] for row in records),
        "output_path": "revision/model3/phase22/outputs/phase22h_paired_generations.json",
        "output_sha256": output_hash,
        "record_ids_canonical_sha256": canonical_sha256([row["record_id"] for row in records]),
        "heldout_generation_run": True,
        "scanner_run": False,
    }
    atomic_json(FINAL_MANIFEST, final)
    run_state.update({
        "status": "COMPLETE",
        "completed_records": len(worklist),
        "output_sha256": output_hash,
        "generation_manifest_sha256": sha256_file(FINAL_MANIFEST),
    })
    atomic_json(RUN_MANIFEST, run_state)
    print(json.dumps(final, indent=2))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--preflight-only", action="store_true")
    parser.add_argument("--resume", action="store_true")
    args = parser.parse_args()
    print(json.dumps(preflight(args.resume), indent=2))
    if not args.preflight_only:
        require(not OUTPUT.exists() and not FINAL_MANIFEST.exists(), "immutable paired output already exists")
        run(args.resume)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        raise
